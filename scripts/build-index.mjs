#!/usr/bin/env node
// Writes shared/course-index.js: the small part of the course the server
// needs (line ids, chapters, ratings, and the ids of each personal deck), so
// the Worker doesn't have to carry the full course data.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const course = JSON.parse(fs.readFileSync(path.join(ROOT, 'shared/course.json'), 'utf8'));
const lines = course.lines.map((l) => ({ id: l.id, chapter: l.chapter, rating: l.rating, blackMoves: l.blackMoves }));
const chapters = course.chapters.map((c) => ({ id: c.id, name: c.name, lines: c.lines.length }));

const decks = {};
const dir = path.join(ROOT, 'shared/personal');
if (fs.existsSync(dir)) {
  for (const f of fs.readdirSync(dir).filter((f) => f.endsWith('.json'))) {
    const d = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
    decks[d.user.toLowerCase()] = d.items.map((it) => {
      const quietPunish = it.kind === 'punish' && !/x/.test(it.best);
      const rating = (it.kind === 'mistake' ? 1250 : quietPunish ? 1250 : 1050) + (it.found ? 0 : 100);
      return { id: it.id, kind: it.kind, chapter: it.chapter, rating };
    });
  }
}

const out = `// Generated by scripts/build-index.mjs from shared/course.json and shared/personal/*.json. Do not edit.
export const LINES = ${JSON.stringify(lines)};
export const CHAPTERS = ${JSON.stringify(chapters)};
export const DECKS = ${JSON.stringify(decks)};
export const LINE_BY_ID = Object.fromEntries(LINES.map((l) => [l.id, l]));
`;
fs.writeFileSync(path.join(ROOT, 'shared/course-index.js'), out);
console.log(`course-index: ${lines.length} lines, decks: ${Object.entries(decks).map(([u, d]) => `${u} (${d.length})`).join(', ') || 'none'}`);
